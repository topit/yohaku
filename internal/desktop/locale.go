// T returns interface text in the saved language. Language changes are not
// previewed: saving commits both our labels and MyGo's native control locale.
func (a *App) T(source string) string {
	if a.prefs.Language == "zh-Hans" {
		if text, ok := chinese[source]; ok {
			return text
		}
	}
	return source
}
